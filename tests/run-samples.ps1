<#
.SYNOPSIS
    End-to-end sample test for PlantDownRca.exe.

.DESCRIPTION
    Copies tests\SampleLogs into tests\_work, rewrites the sample dates to TODAY (so the
    incident window always covers them), generates plant.config.xml pointing at those
    copies, runs the collector in CLI mode, and then asserts that the report, timeline,
    grouped issues, pattern tags, SQL explanation-merge, stack-trace attachment and the
    untimed section all came out right.

    Nothing outside tests\_work is written. No database and no network access needed.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tests\run-samples.ps1
#>
[CmdletBinding()]
param(
    # Path to PlantDownRca.exe. Defaults to the Release build in the repo.
    [string]$Exe
)

$ErrorActionPreference = 'Stop'

$testsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoDir  = Split-Path -Parent $testsDir
$workDir  = Join-Path $testsDir '_work'
$checks   = New-Object System.Collections.Generic.List[object]

function Assert-True {
    param([bool]$Condition, [string]$Name, [string]$Detail = '')
    $script:checks.Add([pscustomobject]@{ Ok = $Condition; Name = $Name; Detail = $Detail })
}

# ---------- 1. Locate (or build) the exe ----------
if (-not $Exe) {
    $Exe = Join-Path $repoDir 'src\PlantDownRca\bin\Release\PlantDownRca.exe'
}
if (-not (Test-Path $Exe)) {
    Write-Host "Building Release binary (not found at $Exe)..." -ForegroundColor Yellow
    $msbuild = @(
        "${env:ProgramFiles}\Microsoft Visual Studio\2022\*\MSBuild\Current\Bin\MSBuild.exe",
        "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2022\*\MSBuild\Current\Bin\MSBuild.exe",
        "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2019\*\MSBuild\Current\Bin\MSBuild.exe"
    ) | ForEach-Object { Get-Item $_ -ErrorAction SilentlyContinue } | Select-Object -First 1

    if (-not $msbuild) { throw "PlantDownRca.exe not found and MSBuild could not be located. Build the solution first." }
    & $msbuild.FullName (Join-Path $repoDir 'PlantDownRca.sln') /p:Configuration=Release /v:minimal /nologo
    if ($LASTEXITCODE -ne 0) { throw "Build failed." }
}
if (-not (Test-Path $Exe)) { throw "Exe still missing after build: $Exe" }

# ---------- 2. Fresh working copies of the sample logs ----------
if (Test-Path $workDir) { Remove-Item $workDir -Recurse -Force }
New-Item -ItemType Directory -Path $workDir | Out-Null
$sampleOut = Join-Path $workDir 'SampleLogs'
Copy-Item (Join-Path $testsDir 'SampleLogs') $sampleOut -Recurse

# ---------- 3. Rebase the sample dates onto today ----------
$today = Get-Date
$isoDate = $today.ToString('yyyy-MM-dd')    # 2026-10-15 -> 2026-10-16
$usDate  = $today.ToString('M/d/yyyy')      # 10/15/2026 -> 10/16/2026
$evtDate = $today.ToString('dd-MMM-yyyy')   # 15-Oct-2026 -> 16-Oct-2026

Get-ChildItem $sampleOut -Recurse -File | ForEach-Object {
    $content = Get-Content -Raw -LiteralPath $_.FullName
    $content = $content.Replace('2026-10-15', $isoDate).Replace('10/15/2026', $usDate).Replace('15-Oct-2026', $evtDate)
    Set-Content -LiteralPath $_.FullName -Value $content -NoNewline -Encoding UTF8
}

# ---------- 4. Generate a config that points only at the sample folders ----------
$cfgPath = Join-Path $workDir 'plant.config.xml'
$from    = $isoDate + ' 00:00:00'
$to      = $isoDate + ' 23:59:59'
$outDir  = Join-Path $workDir 'out'

@"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tests\run-samples.ps1 - sample data only, no real server is contacted. -->
<AppConfig>
  <PlantName>Sample Plant (automated test)</PlantName>
  <ServerRole>App</ServerRole>
  <DiscoveryEnabled>false</DiscoveryEnabled>
  <IncludeWarnings>true</IncludeWarnings>
  <EnableSqlQueries>false</EnableSqlQueries>
  <AppLogFolders>
    <Folder>$sampleOut\AppLogs</Folder>
  </AppLogFolders>
  <SqlLogFolders>
    <Folder>$sampleOut\SqlLogs</Folder>
  </SqlLogFolders>
  <KepwareLogFolders>
    <Folder>$sampleOut\KepwareLogs</Folder>
  </KepwareLogFolders>
  <EventLogChannels />
  <ServicesToCheck />
  <SqlQueryConnections />
  <SqlQueries />
</AppConfig>
"@ | Set-Content -LiteralPath $cfgPath -Encoding UTF8

# ---------- 5. Run the collector ----------
Write-Host "Running: $Exe" -ForegroundColor Cyan
Write-Host "Window : $from  ->  $to" -ForegroundColor Cyan
& $Exe --from $from --to $to --config $cfgPath --out $outDir
Assert-True ($LASTEXITCODE -eq 0) 'Process exits with code 0' "exit code $LASTEXITCODE"

# ---------- 6. Assertions ----------
$reportPath   = Join-Path $outDir 'Report.html'
$csvPath      = Join-Path $outDir 'timeline.csv'
$summaryPath  = Join-Path $outDir 'summary.txt'
$entriesPath  = Join-Path $outDir 'entries.xml'

Assert-True (Test-Path $reportPath)  'Report.html is written'
Assert-True (Test-Path $csvPath)     'timeline.csv is written'
Assert-True (Test-Path $summaryPath) 'summary.txt is written'
Assert-True (Test-Path $entriesPath) 'entries.xml is written'

if (-not (Test-Path $summaryPath)) {
    Write-Host "`nNo output produced - failing." -ForegroundColor Red
    exit 1
}

$summary = Get-Content -Raw -LiteralPath $summaryPath
$report  = Get-Content -Raw -LiteralPath $reportPath
$csv     = Get-Content -Raw -LiteralPath $csvPath
$rows    = @($csv -split "`n" | Where-Object { $_.Trim() -ne '' })

# Dedupe: six "Timeout after Ns for device N" lines must collapse into one 6x group.
Assert-True ($summary -match '\[6x\]') 'Repeated timeouts are deduplicated into one 6x group'
Assert-True ($summary -match 'Timeout after') 'Timeout messages reach the summary'

# Pattern tags (regex rules in Core/TimelineBuilder.cs).
Assert-True ($summary -match 'DISK_FULL')                'Tag DISK_FULL is applied'
Assert-True ($summary -match 'KEPWARE_PLC_COMMS_LOSS')   'Tag KEPWARE_PLC_COMMS_LOSS is applied'
Assert-True ($summary -match 'SERVICE_CRASHED')          'Tag SERVICE_CRASHED is applied'
Assert-True ($summary -match 'SQL_DEADLOCK')             'Tag SQL_DEADLOCK is applied'
Assert-True ($summary -match 'SQL_FAILOVER_OR_AG_MOVE')  'Tag SQL_FAILOVER_OR_AG_MOVE is applied'

# SQL ERRORLOG: "Error: 9002" + its explanation line 20 ms later must merge into one entry.
Assert-True ($report -match 'is full due to') 'SQL error explanation line is merged into its error'
# Multi-line entry: stack trace stays attached to the socket error.
Assert-True ($report -match 'SocketException') 'Stack trace stays attached to its error'
# Untimed lines are never dropped.
Assert-True ($report -match 'Untimed Entries') 'Untimed entries section is present'

# Coverage across all three file sources.
Assert-True ($csv -match 'AppLog')  'Application log entries in timeline.csv'
Assert-True ($csv -match ',SQL,')   'SQL ERRORLOG entries in timeline.csv'
Assert-True ($csv -match 'Kepware') 'Kepware entries in timeline.csv'
Assert-True ($rows.Count -ge 15)    "timeline.csv has at least 15 rows (got $($rows.Count))"

# ---------- 7. Verdict ----------
Write-Host ''
$failed = @($checks | Where-Object { -not $_.Ok })
foreach ($c in $checks) {
    if ($c.Ok) { Write-Host ("  PASS  " + $c.Name) -ForegroundColor Green }
    else       { Write-Host ("  FAIL  " + $c.Name + '  ' + $c.Detail) -ForegroundColor Red }
}
Write-Host ''
if ($failed.Count -eq 0) {
    Write-Host "ALL $($checks.Count) CHECKS PASSED. Report: $reportPath" -ForegroundColor Green
    exit 0
}
Write-Host "$($failed.Count) of $($checks.Count) CHECKS FAILED." -ForegroundColor Red
exit 1
